// Función para generar fechas relativas a hoy para que la cartelera siempre esté viva
function getRelativeDate(daysOffset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().split('T')[0];
}

